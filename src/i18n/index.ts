export type TranslationKey = keyof (typeof translations)["en"];

let cachedLanguage: SupportedLanguage | null = null;

export function getDeviceLanguage(): SupportedLanguage {
  if (cachedLanguage) return cachedLanguage;
  try {
    const code = Localization.getLocales()?.[0]?.languageCode ?? "en";
    cachedLanguage = (SUPPORTED_LANGUAGES as string[]).includes(code)
      ? (code as SupportedLanguage)
      : "en";
  } catch {
    cachedLanguage = "en";
  }
  return cachedLanguage;
}

/** Test seam — the device language is read once and cached for the session. */
export function resetLanguageCache(): void {
  cachedLanguage = null;
}

/**
 * The CLDR plural category for `count` in the active language — "one"/"other"
 * in English, but also "few"/"many" in Russian and six forms in Arabic. Using
 * the real rules is what stops a Russian player reading "Осталось 2 попыток".
 */
function pluralCategory(count: number, lang: string): string {
  try {
    return new Intl.PluralRules(lang).select(count);
  } catch {
    return count === 1 ? "one" : "other";
  }
}

export function t(
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const lang = getDeviceLanguage();
  const dict = translations[lang] ?? translations.en;

  // A key may carry plural variants as suffixed siblings ("guessesLeft_one").
  // Keys without variants resolve unchanged, so the mechanism is invisible to
  // every other string.
  let resolved: string = key;
  if (params && typeof params.count === "number") {
    const variant = `${key}_${pluralCategory(params.count, lang)}`;
    if ((dict as Record<string, string>)[variant]) resolved = variant;
    else if ((translations.en as Record<string, string>)[variant])
      resolved = variant;
  }

  const table = dict as Record<string, string>;
  const fallback = translations.en as Record<string, string>;
  let text =
    table[resolved] ?? fallback[resolved] ?? table[key] ?? fallback[key] ?? key;

  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

/** True when the active language mirrors the layout. */
export const isRTLLanguage = (): boolean =>
  (RTL_LANGUAGES as string[]).includes(getDeviceLanguage());
